import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, readFile, writeFile, mkdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { renderFoundations, writeOrCheck } from "./foundations.mjs";
import { parseComponentMetadata } from "./documents.mjs";

const tokens = JSON.parse(await readFile(new URL("../tokens.json", import.meta.url), "utf8"));
test("component contracts require discoverable metadata and a usage/behavior/accessibility structure", async () => {
  const valid = await readFile(new URL("../src/conversation/thinking-status/thinking-status.md", import.meta.url), "utf8");
  const data = parseComponentMetadata(valid, "thinking-status.md");
  assert.ok(data.related.includes("activity-group"));
  assert.throws(() => parseComponentMetadata(valid.replace(/^category:.*\n/m, ""), "broken.md"), /missing category/);
  assert.throws(() => parseComponentMetadata(valid.replace("## 可访问性", "## 其他"), "broken.md"), /missing section.*可访问性/);
});
test("existing control geometry and default palette remain explicit", () => {
  const result = renderFoundations(tokens);
  assert.match(result.foundation, /--spacing-field: 16px;/);
  assert.match(result.tailwind, /--text-ui-base: var\(--ui-font-size\);/);
  assert.match(result.tailwind, /--radius-button: 8px;/);
  assert.deepEqual(result.themes.light, { background: "#ffffff", foreground: "#1a1c1f", accent: "#3a83f7", contrast: 45 });
  assert.deepEqual(result.themes.dark, { background: "#181818", foreground: "#ffffff", accent: "#3a83f7", contrast: 60 });
});
test("two tokens cannot claim the same CSS role", () => {
  const broken = structuredClone(tokens);
  broken.foundation.duplicate = { ...broken.foundation["spacing-field"], $extensions: { "build.areal.ui": { name: "spacing-field" } } };
  assert.throws(() => renderFoundations(broken), /duplicate.*spacing-field/);
});
test("CSS expressions require an explicit extension", () => {
  const broken = structuredClone(tokens);
  delete broken.foundation["spacing-control"].$extensions;
  assert.throws(() => renderFoundations(broken), /CSS expression.*spacing-control/);
});
test("guard detects a dark theme whose foreground is unreadable", () => {
  const broken = structuredClone(tokens);
  broken.themes.foreground.$extensions["build.areal.ui"].dark = broken.themes.background.$extensions["build.areal.ui"].dark;
  assert.throws(() => renderFoundations(broken), /dark.*contrast/);
});
test("check rejects edited generated bytes without overwriting them", async () => {
  const root = await mkdtemp(join(tmpdir(), "areal-ui-assets-"));
  await mkdir(join(root, "generated"));
  const path = join(root, "generated/foundation.css");
  await writeOrCheck(path, "expected\n", false);
  await writeFile(path, "edited\n");
  await assert.rejects(writeOrCheck(path, "expected\n", true), /out of date/);
  assert.equal(await readFile(path, "utf8"), "edited\n");
});
