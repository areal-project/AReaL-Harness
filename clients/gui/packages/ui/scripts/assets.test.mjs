test("experimental consumers require exact entries and reject stale allowances", async (t) => {
  const { verifyExperimentalImports } = await import("./documents.mjs");
  const root = await mkdtemp(join(tmpdir(), "areal-ui-entries-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(join(root, "renderer/src"), { recursive: true });
  await writeFile(
    join(root, "renderer/src/consumer.ts"),
    'import { Spinner } from "@areal/ui/experimental";\n',
  );
  const allowance = {
    file: "renderer/src/consumer.ts",
    symbol: "Spinner",
    owner: "GUI component owner",
    exitCondition: "Assess contract and production consumers before graduation.",
  };
  await assert.rejects(
    verifyExperimentalImports(root, []),
    /unlisted experimental import.*Spinner/,
  );
  assert.equal(await verifyExperimentalImports(root, [allowance]), 1);
  await writeFile(join(root, "renderer/src/consumer.ts"), 'import { Button } from "@areal/ui";\n');
  await assert.rejects(
    verifyExperimentalImports(root, [allowance]),
    /stale experimental allowance.*Spinner/,
  );
  for (const entry of ["wip", "src/internal"]) {
    await writeFile(
      join(root, "renderer/src/consumer.ts"),
      `import { Spinner } from "@areal/ui/${entry}";\n`,
    );
    await assert.rejects(verifyExperimentalImports(root, []), /retired or deep UI import/);
  }
  for (const entry of ["experimental", "wip", "src/internal"]) {
    await writeFile(
      join(root, "renderer/src/consumer.ts"),
      `const lazy = () => import("@areal/ui/${entry}");\n`,
    );
    await assert.rejects(verifyExperimentalImports(root, []), /UI import/);
  }
});

test("palette role metadata covers actual variables and aliases resolve to known roles", async () => {
  const { renderTokenReference } = await import("./foundations.mjs");
  const result = renderFoundations(tokens);
  const paletteVariables = () => ({ "--color-background": "#ffffff" });
  const missing = structuredClone(tokens);
  missing.palette = { roles: {} };
  assert.throws(
    () => renderTokenReference(missing, result.themes, paletteVariables),
    /palette metadata.*color-background/,
  );
  const invalid = structuredClone(tokens);
  invalid.palette.roles["--color-background"].alias = "--color-missing";
  assert.throws(
    () => renderTokenReference(invalid, result.themes, paletteVariables),
    /unknown palette alias/,
  );
});

test("palette generation rejects unknown, cyclic, and backwards dependencies", async () => {
  const { renderPalette } = await import("./palette.mjs");
  const unknown = structuredClone(tokens);
  unknown.palette.semantic["surface-base"].value = { semantic: "missing" };
  assert.throws(() => renderPalette(unknown), /unknown semantic.*missing/);
  const cyclic = structuredClone(tokens);
  cyclic.palette.semantic["surface-base"].value = { semantic: "surface-base" };
  assert.throws(() => renderPalette(cyclic), /cyclic semantic.*surface-base/);
  const backwards = structuredClone(tokens);
  backwards.palette.roles["--color-result-card"].value = { input: "background" };
  assert.throws(() => renderPalette(backwards), /component.*semantic reference/);
  const unknownParameter = structuredClone(tokens);
  unknownParameter.palette.semantic["surface-raised"].value.mix.percent = "missing";
  assert.throws(() => renderPalette(unknownParameter), /unknown parameter.*missing/);
  const badDefault = structuredClone(tokens);
  badDefault.palette.semantic["text-primary-inverse"].defaultOverrides[0].match.background =
    "missing";
  assert.throws(() => renderPalette(badDefault), /unknown reference.*missing/);
});

test("theme source only retains documented color algorithms", async () => {
  const { verifyThemeSource } = await import("./foundations.mjs");
  const source = await readFile(new URL("../src/theme.ts", import.meta.url), "utf8");
  verifyThemeSource(source);
  assert.throws(
    () => verifyThemeSource(source + '\nconst hiddenColor = "#123456";'),
    /color literal/,
  );
  assert.throws(
    () => verifyThemeSource(source + "\nconst hiddenParameter = 21;"),
    /numeric parameter/,
  );
  assert.throws(() => verifyThemeSource(source.replace("0.2126", "0.2")), /algorithm constant/);
});

test("every motion token has a system and explicit reduced-motion override", () => {
  const future = structuredClone(tokens);
  future.foundation["motion-panel"] = { ...future.foundation["motion-fast"] };
  const css = renderFoundations(future).foundation;
  assert.match(css, /@media \(prefers-reduced-motion: reduce\)/);
  for (const name of Object.keys(future.foundation).filter((name) => name.startsWith("motion-"))) {
    const reduced = name === "motion-loop" ? "0" : "0ms";
    assert.equal(
      css.split(`--${name}: ${reduced};`).length - 1,
      2,
      `${name} must follow both preference sources`,
    );
  }
  future.foundation["motion-bounce"] = { ...future.foundation["ease-standard"] };
  assert.throws(() => renderFoundations(future), /missing reduced motion value: motion-bounce/);
});

