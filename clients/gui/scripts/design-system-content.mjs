import assert from 'node:assert/strict';
import { join } from 'node:path';
export async function runContentSystem(page, scratch, checks) {
  const region = page.getByRole('region', { name: '内容与决策系统', exact: true });
  await region.waitFor();
  const approval = region.getByRole('region', { name: '审批预览', exact: true });
  const question = region.getByRole('region', { name: '提问预览', exact: true });
  const records = region.getByLabel('预览调用记录', { exact: true });
  const progress = region.getByRole('region', { name: '过程预览', exact: true });
  assert.equal(await progress.locator('.turn-progress-summary').innerText(), 'Working for 15m 29s');
  assert.equal(await progress.locator('.turn-failure-indicator').count(), 1);
  assert.equal(await progress.getByText('不应默认出现的失败工具行').count(), 0);
  await progress.locator('.turn-failure-indicator > summary').click();
  assert.match(await progress.locator('.turn-failure-details').innerText(), /审批拒绝/);
  await progress.locator('.turn-failure-indicator > summary').click();
  assert.equal(await approval.locator('.decision-card-details').getAttribute('open'), null);
  const command = await approval.locator('.approval-command-summary > code').evaluate(el => ({ height: el.clientHeight, line: parseFloat(getComputedStyle(el).lineHeight) }));
  assert.ok(command.height <= command.line * 2 + 1, JSON.stringify(command));
  await approval.getByText('查看完整请求', { exact: true }).click();
  await approval.locator('.approval-preview').waitFor({ state: 'visible' });
  assert.match(await approval.locator('.approval-preview').innerText(), /原始参数保留/);
  await approval.getByText('查看完整请求', { exact: true }).click();
  await question.getByRole('radio').first().click();
  assert.match(await records.innerText(), /响应次数：0/);
  await question.getByRole('button', { name: '稍后回答', exact: true }).click();
  await question.getByRole('button', { name: '展开待回答问题', exact: true }).click();
  assert.equal(await question.getByRole('radio').first().isChecked(), true);
  await question.getByRole('button', { name: '发送', exact: true }).click();
  assert.match(await records.innerText(), /响应次数：1/);
  await approval.screenshot({ path: join(scratch, 'approval-compact.png'), animations: 'disabled' });
  await progress.screenshot({ path: join(scratch, 'working-compact.png'), animations: 'disabled' });
  checks.push('Working duration; one inspectable failure indicator; collapsed original approval; explicit question submit and draft retention');
  assert.equal(await region.locator('.areal-native-content').count(), 6);
  const diagram = region.getByRole('region', { name: 'mermaid 代码', exact: true });
  await diagram.scrollIntoViewIfNeeded();
  await diagram.locator('[data-streamdown="mermaid-block"] svg:has(.node)').waitFor();
  assert.match(await diagram.locator('[data-streamdown="mermaid-block"] svg:has(.node)').textContent(), /输入/);
  await diagram.getByRole('button', { name: '查看源码', exact: true }).click();
  await diagram.locator('.conversation-code-content').waitFor({ state: 'visible' });
  await diagram.getByRole('button', { name: '预览图形', exact: true }).click();
  await diagram.locator('.conversation-code-preview').waitFor({ state: 'visible' });
  await diagram.screenshot({ path: join(scratch, 'mermaid-light.png'), animations: 'disabled' });
  const lightDiagram = await diagram.locator('[data-streamdown="mermaid-block"] svg .node rect').first().evaluate(el => getComputedStyle(el).fill);
  await page.getByLabel('主题', { exact: true }).selectOption('dark');
  await page.waitForFunction(light => { const el = document.querySelector('.conversation-code-preview [data-streamdown="mermaid-block"] svg .node rect'); return el && getComputedStyle(el).fill !== light; }, lightDiagram);
  await diagram.screenshot({ path: join(scratch, 'mermaid-dark.png'), animations: 'disabled' });
  await page.getByLabel('主题', { exact: true }).selectOption('light');
  checks.push('Mermaid renders a visible diagram, switches to preserved source and updates for dark theme');
  await region.locator('.katex').first().waitFor();
  assert.ok(await region.locator('.katex-mathml math').count() >= 2);
  assert.match(await region.getByRole('region', { name: '混合内容预览' }).innerText(), /价格 \$5-\$10/);
  await region.locator('[data-content-type="bar-chart"]').getByText('查看数据', { exact: true }).click();
  await region.locator('[data-content-type="bar-chart"] pre').waitFor({ state: 'visible' });
  await page.screenshot({ path: join(scratch, 'content-light.png'), fullPage: true, animations: 'disabled' });
  await page.getByLabel('内容状态', { exact: true }).selectOption('streaming');
  await region.locator('[data-content-kind="pending"]').waitFor();
  assert.equal(await region.locator('.areal-native-content').count(), 0);
  await page.getByLabel('内容状态', { exact: true }).selectOption('invalid');
  await region.getByText('内容暂不可用，查看原文', { exact: true }).click();
  assert.match(await region.locator('.conversation-content-fallback pre').innerText(), /<script>bad/);
  assert.equal(await region.locator('script').count(), 0);
  await page.getByLabel('内容状态', { exact: true }).selectOption('diagram-streaming');
  await diagram.locator('.conversation-code-content').waitFor({ state: 'visible' });
  assert.equal(await diagram.locator('.conversation-code-preview').count(), 0, 'incomplete streaming diagram stays source-only');
  await page.getByLabel('内容状态', { exact: true }).selectOption('diagram-error');
  await diagram.scrollIntoViewIfNeeded();
  await diagram.getByText('图形暂无法预览，可切换源码查看。', { exact: true }).waitFor();
  await diagram.getByRole('button', { name: '查看源码', exact: true }).click();
  await diagram.locator('.conversation-code-content').waitFor({ state: 'visible' });
  await diagram.screenshot({ path: join(scratch, 'mermaid-error-source.png'), animations: 'disabled' });
  checks.push('Mermaid incomplete streams do not render; syntax errors retain inspectable source');
  checks.push('six read-only native variants, math/MathML/chemistry, currency literal, chart data, streaming placeholder and escaped unsupported source');
  for (const state of ['busy', 'unknown']) {
    await page.getByLabel('响应状态', { exact: true }).selectOption(state);
    await approval.getByRole('button', { name: '允许一次', exact: true }).click();
    if (state === 'busy') assert.equal(await approval.getByRole('button', { name: '允许一次', exact: true }).isDisabled(), true);
    else { await approval.getByRole('button', { name: '核对待审批状态', exact: true }).waitFor(); assert.equal(await approval.getByRole('button', { name: '允许一次', exact: true }).count(), 0); }
    assert.match(await records.innerText(), /响应次数：1/);
  }
  await page.getByLabel('响应状态', { exact: true }).selectOption('ready');
  await page.getByLabel('问题类型', { exact: true }).selectOption('multi');
  await question.getByRole('radio').first().click();
  await question.getByRole('button', { name: '下一题', exact: true }).click();
  await question.getByRole('textbox').fill('保留第二题回答');
  await question.getByRole('button', { name: '上一题', exact: true }).click();
  assert.equal(await question.getByRole('radio').first().isChecked(), true);
  assert.match(await records.innerText(), /响应次数：0/);
  await question.getByRole('button', { name: '下一题', exact: true }).click();
  assert.equal(await question.getByRole('textbox').inputValue(), '保留第二题回答');
  await question.getByRole('button', { name: '发送', exact: true }).click();
  assert.match(await records.innerText(), /响应次数：1/);
  await page.getByLabel('主题', { exact: true }).selectOption('dark');
  await page.getByLabel('字号', { exact: true }).selectOption('18');
  await page.getByLabel('面板宽度', { exact: true }).selectOption('narrow');
  await page.getByLabel('问题类型', { exact: true }).selectOption('long');
  const alignment = await question.locator('.ask-user-option').first().evaluate(el => ({ row: el.getBoundingClientRect().top, number: el.querySelector('.ask-user-number').getBoundingClientRect().top }));
  assert.ok(alignment.number - alignment.row >= 0 && alignment.number - alignment.row < 20, JSON.stringify(alignment));
  const overflow = await region.evaluate(el => ({ width: el.clientWidth, full: el.scrollWidth }));
  assert.ok(overflow.full <= overflow.width + 1, JSON.stringify(overflow));
  await page.getByLabel('内容状态', { exact: true }).selectOption('ready');
  await diagram.scrollIntoViewIfNeeded();
  await diagram.locator('[data-streamdown="mermaid-block"] svg:has(.node)').waitFor();
  const diagramWidth = await diagram.evaluate(el => ({ width: el.clientWidth, full: el.scrollWidth }));
  assert.ok(diagramWidth.full <= diagramWidth.width + 1, JSON.stringify(diagramWidth));
  await diagram.screenshot({ path: join(scratch, 'mermaid-dark-narrow.png'), animations: 'disabled' });
  await question.getByRole('button', { name: '发送', exact: true }).scrollIntoViewIfNeeded();
  await question.screenshot({ path: join(scratch, 'question-dark-narrow.png'), animations: 'disabled' });
  await page.screenshot({ path: join(scratch, 'content-dark-narrow.png'), fullPage: true, animations: 'disabled' });
  await page.getByLabel('响应状态', { exact: true }).selectOption('ready');
  for (const kind of ['browser-long', 'shell-long', 'computer-long', 'file-long']) {
    await page.getByLabel('审批类型', { exact: true }).selectOption(kind);
    const card = approval.locator('.decision-card');
    await card.scrollIntoViewIfNeeded();
    assert.equal(await card.locator('.decision-card-details').getAttribute('open'), null);
    const initial = await card.evaluate(el => ({ height: el.getBoundingClientRect().height, width: el.clientWidth, full: el.scrollWidth }));
    assert.ok(initial.height <= 360, `${kind} default summary must stay compact: ${JSON.stringify(initial)}`);
    assert.ok(initial.full <= initial.width + 1, `${kind} must not scroll horizontally`);
    if (kind === 'browser-long' || kind === 'shell-long') {
      const preview = card.locator('.approval-command-summary > code');
      assert.equal(await preview.count(), 1);
      assert.ok(await preview.evaluate(el=>el.clientHeight<=parseFloat(getComputedStyle(el).lineHeight)*2+1));
    }
    await approval.screenshot({ path: join(scratch, `${kind}-collapsed.png`), animations: 'disabled' });
    await card.getByText('查看完整请求', { exact: true }).click();
    const details = card.locator('.decision-card-details > div');
    const full = await details.textContent();
    assert.ok(full.includes('REASON_END') && full.includes('TARGET_END') && full.includes('COMMAND_END'), `${kind} keeps every original field on demand`);
    const footer = await card.locator('.decision-card-footer').evaluate(el => { const r=el.getBoundingClientRect(); return {top:r.top,bottom:r.bottom}; });
    assert.ok(footer.top >= 0 && footer.bottom <= await page.evaluate(()=>innerHeight), `${kind} decision actions remain visible`);
    await card.locator('.decision-card-body').evaluate(el=>el.scrollTo(0,el.scrollHeight));
    assert.equal(await card.locator('.decision-card-body').evaluate(el=>el.scrollWidth > el.clientWidth + 1), false);
    await approval.screenshot({ path: join(scratch, `${kind}-expanded.png`), animations: 'disabled' });
    await card.locator('.decision-card-body').evaluate(el=>el.scrollTo(0,0));
    await card.getByText('查看完整请求', { exact: true }).click();
    await card.getByRole('button',{name:'允许一次',exact:true}).click();
    assert.match(await records.innerText(), /响应次数：1/);
    assert.equal(await card.getByRole('button',{name:'允许一次',exact:true}).isDisabled(), true);
  }
  checks.push('all approval types: dark18 narrow compact summaries, complete original reasons/targets/commands on demand, visible footer and acknowledged submission lock');
  checks.push('busy/unknown approval locks; multiple-question drafts; explicit batch submission; dark18 narrow long-option footer reachability');
}
