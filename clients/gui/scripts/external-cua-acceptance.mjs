import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile, rm, mkdir, copyFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const filesystem = require('node:fs/promises');
const originalAccess = filesystem.access;
let nextAccess;
filesystem.access = async (...args) => { if (nextAccess) { const barrier = nextAccess; nextAccess = null; barrier.enter(); await barrier.wait; } return originalAccess(...args); };
const { ExternalCua } = require('../app/src/core/external-cua.cjs');
const directory = await mkdtemp(join(tmpdir(), 'areal-cua-'));
const evidence = resolve('.scratch/lcu-integration/subprocess');
await mkdir(evidence, { recursive: true });
const log = join(directory, 'events.jsonl'), executable = join(directory, 'lcu');
const fixture = resolve(import.meta.dirname, 'fixtures/external-cua/runtime.mjs');
await writeFile(executable, `#!/bin/sh\nexec '${process.execPath}' '${fixture}' '${log}'\n`, { mode: 0o700 });
let selection = { enabled: true, provider: 'lcu', executable };
let answer = { action: 'accept', content: {} };
let host = new ExternalCua({ getSelection: () => selection, getAvailable: () => true,
  onElicitation: async () => answer });
const owner = { projectId: 'project', coreInstanceId: 'core', coreGeneration: 'generation', toolHostGeneration: 'host', threadId: 'thread', turnId: 'turn', callId: 'call', cwd: directory };
try {
  for (const size of [32768, 32769]) {
    await writeFile(join(directory, 'instruction-bytes'), String(size));
    const boundary = new ExternalCua({ getSelection: () => selection, getAvailable: () => true, onElicitation: async () => answer });
    if (size === 32768) assert.equal((await boundary.catalog(owner)).instructions.length, size);
    else await assert.rejects(boundary.catalog(owner), /32768-byte/);
    await boundary.close();
  }
  await rm(join(directory, 'instruction-bytes'));
  const catalog = await host.catalog({ ...owner });
  assert.ok(catalog.instructions.length > 8192);
  assert.ok(catalog.instructions.endsWith('ORIGINAL INSTRUCTIONS END'));
  assert.deepEqual(catalog.tools.map(tool => tool.name), ['js', 'js_reset']);
  assert.deepEqual(catalog.tools[0].outputSchema, { type: 'object', additionalProperties: true });
  const call = (code, extra = {}) => host.call({ ...owner, tool: 'js', arguments: { code }, definition: catalog.tools[0], clientInstructions: catalog.instructions, ...extra });
  const first = JSON.parse((await call('count')).content[0].text);
  assert.equal(first.value, 1);
  assert.deepEqual(first.metadata['x-codex-turn-metadata'], { session_id: 'thread', turn_id: 'turn', call_id: 'call', thread_id: 'thread' });
  await host.endTurn({ ...owner, event: 'Stop' });
  owner.turnId = 'next';
  assert.equal(JSON.parse((await call('count')).content[0].text).value, 2);
  assert.equal(JSON.parse((await call('count', { threadId: 'other' })).content[0].text).value, 1);
  for (const expected of [{ action: 'accept', content: {} }, { action: 'decline' }, { action: 'cancel' }]) {
    answer = expected;
    assert.deepEqual(JSON.parse((await call('approval')).content[0].text).approval, expected);
  }
  assert.equal((await call('image')).content[1].type, 'image');
  assert.equal((await call('error')).isError, true);
  await host.revokeProject({ ...owner, toolHostGeneration: 'retired-host' });
  assert.equal(host.status().active, true);
  assert.equal((await call('count')).isError, undefined);
  let entered, release;
  const atAccess = new Promise(resolve => { entered = resolve; });
  nextAccess = { enter: entered, wait: new Promise(resolve => { release = resolve; }) };
  const heldCall = call('forbidden-after-stop', { turnId: 'pending-stop' });
  await atAccess;
  await host.stop('user_stop');
  release();
  await assert.rejects(heldCall, /revoked/);
  await assert.rejects(call('forbidden-after-stop', { turnId: 'pending-stop' }), /stopped/);
  await assert.rejects(call('count'), /stopped/);
  owner.turnId = 'fresh';
  const events = (await readFile(log, 'utf8')).trim().split('\n').map(JSON.parse);
  assert.ok(!events.some(event => event.params?.arguments?.code === 'forbidden-after-stop'));
  assert.ok(events.some(event => event.type === 'control' && event.request.type === 'stop' && event.request.app === 'fixture.app'));
  assert.ok(events.some(event => event.params?.arguments?.hook_event_name === 'Stop'));
  assert.ok(events.some(event => event.params?.arguments?.hook_event_name === 'Interrupt'));
  assert.ok(events.filter(event => event.type === 'start').every(event => event.surfaces === 'computer' && !event.inheritedBypass));
  selection = { ...selection, executable: join(directory, 'missing') };
  await assert.rejects(host.catalog(owner), /executable|ENOENT/i);
  selection = { ...selection, executable };
  const fresh = await host.catalog(owner);
  await assert.rejects(host.call({ ...owner, tool: 'js', arguments: { code: 'crash' }, definition: fresh.tools[0], clientInstructions: fresh.instructions }), /UNKNOWN|closed|Connection/i);
  const afterCrash = (await readFile(log, 'utf8')).trim().split('\n').map(JSON.parse);
  assert.equal(afterCrash.filter(event => event.type === 'effect').length, 1);
  await assert.rejects(host.stop('cleanup-after-crash'), /connected|cleanup|closed/i);
  assert.equal(host.status().state, 'quarantined');
  host = new ExternalCua({ getSelection: () => selection, getAvailable: () => true, onElicitation: async () => answer });
  owner.turnId = 'cleanup-test';
  await call('cleanup-failure');
  await writeFile(join(directory, 'block-connect'), 'blocked');
  const connecting = host.catalog({ ...owner, threadId: 'pending-connect' });
  await new Promise(resolve => setTimeout(resolve, 100));
  await assert.rejects(host.endTurn({ ...owner, event: 'Stop' }), /cleanup/);
  await writeFile(join(directory, 'release-connect'), 'released');
  await connecting;
  assert.equal(host.status().state, 'quarantined');
  await host.check();
  assert.equal(host.status().state, 'quarantined');
  await assert.rejects(host.stop('cleanup-failed'), /cleanup/);
  await assert.rejects(host.stop('cleanup-failed-again'), /cleanup/);
  assert.equal(host.status().state, 'quarantined');
  await writeFile(join(evidence, 'result.json'), JSON.stringify({ passed: true, nativeInput: false, realRuntime: false }, null, 2));
  console.log('External CUA subprocess acceptance passed:', evidence);
} finally { await host.close().catch(() => {}); await copyFile(log, join(evidence, 'events.jsonl')).catch(() => {}); await rm(directory, { recursive: true, force: true }); }
