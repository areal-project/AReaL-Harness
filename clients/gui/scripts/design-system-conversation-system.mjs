import assert from "node:assert/strict";
import { join } from "node:path";

// Renderer-only acceptance, driven by the published conversation-flow brief.
export async function runConversationSystem(page, scratch, checks) {
  await page.setViewportSize({ width: 1440, height: 1100 });
  const preview = page.getByRole("region", { name: "对话流设计预览", exact: true });
  const activity = preview.getByRole("button", { name: "读取文件、运行命令 · 30 项活动", exact: true });
  const image = preview.getByRole("button", { name: "已查看图片 · 界面参考.png", exact: true });
  const sources = preview.getByRole("region", { name: "输入来源", exact: true });
  const contextToggle = preview.getByRole("button", { name: "任务上下文", exact: true });
  const card = preview.getByRole("complementary", { name: "任务上下文", exact: true });
  assert.equal(await contextToggle.getAttribute("aria-expanded"), "false");
  assert.equal(await card.isVisible(), false, "context card is closed before its top button is used");
  await contextToggle.click();
  await card.waitFor();
  await card.getByRole("heading", { name: "任务上下文", exact: true }).press("Escape");
  assert.equal(await contextToggle.getAttribute("aria-expanded"), "false");
  await contextToggle.click();
  await activity.waitFor();
  assert.equal(await activity.getAttribute("aria-expanded"), "false");
  assert.equal(await image.getAttribute("aria-expanded"), "false");
  assert.equal(await sources.getByRole("button", { name: /^查看来源：/ }).count(), 3);
  await activity.focus(); await activity.press("Enter");
  const list = preview.getByRole("region", { name: "分组活动列表", exact: true });
  await list.waitFor();
  assert.equal(await list.locator("[data-tool-id]").count(), 30);
  const geometry = await list.evaluate(element => ({ vertical: element.scrollHeight > element.clientHeight, horizontal: element.scrollWidth > element.clientWidth + 1 }));
  assert.equal(geometry.vertical, true);
  assert.equal(geometry.horizontal, false);
  await list.hover(); await page.mouse.wheel(0, 260);
  await page.waitForFunction(() => document.querySelector('[aria-label="分组活动列表"]').scrollTop > 0);
  await list.evaluate(element => element.scrollTo(0, 0));
  const command = list.locator('[data-tool-id="system-command"]').getByRole("button").first();
  await command.click();
  await list.getByText("工作目录：/preview/AReaL-Harness", { exact: true }).waitFor();
  await list.getByRole("button", { name: "展开完整命令", exact: true }).click();
  const commandLayout = await list.evaluate(element => {
    const input = element.querySelector('.command-input').getBoundingClientRect();
    const output = element.querySelector('.command-output').getBoundingClientRect();
    return { noOverlap: input.bottom <= output.top, horizontal: element.scrollWidth > element.clientWidth + 1 };
  });
  assert.equal(commandLayout.noOverlap, true, "full command must not overlap output");
  assert.equal(commandLayout.horizontal, false);
  await preview.getByRole("button", { name: "追加命令输出", exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[data-tool-id="system-command"] .command-output').textContent.includes("检查片段 8"));
  assert.equal(await list.evaluate(element => element.scrollWidth <= element.clientWidth + 1), true, "展开长命令和输出后仍没有横向溢出");
  await image.click();
  const picture = preview.getByRole("button", { name: /预览图片.*界面参考/ });
  await picture.waitFor();
  await page.waitForFunction(() => {
    const element = document.querySelector('.areal-image-content img');
    return element?.complete && element.naturalWidth > 0;
  });
  await picture.click();
  await page.getByRole("dialog").waitFor();
  await page.keyboard.press("Escape");
  await page.getByRole("dialog").waitFor({ state: "hidden" });
  await page.screenshot({ path: join(scratch, "conversation-system-dark-expanded.png"), fullPage: true });
  await preview.getByRole("tab", { name: "已完成", exact: true }).click();
  await preview.getByRole("heading", { name: "对话流预览已整理完成", exact: true }).waitFor();
  assert.equal(await activity.getAttribute("aria-expanded"), "true");
  assert.equal(await image.getAttribute("aria-expanded"), "true");
  assert.equal(await command.getAttribute("aria-expanded"), "true");
  await activity.click(); await activity.click();
  assert.equal(await command.getAttribute("aria-expanded"), "true");
  await preview.getByLabel("图片状态", { exact: true }).selectOption("unavailable");
  await image.click();
  await preview.getByRole("status").filter({ hasText: "图片引用暂不可用" }).waitFor();
  await preview.getByLabel("图片状态", { exact: true }).selectOption("available");
  assert.equal(await image.getAttribute("aria-expanded"), "false");
  await image.click();
  checks.push("活动与图片默认收起；30项活动纵向滚动且无横向溢出；真实图片可加载和查看，人工展开跨完成及父组收起保留");

  await sources.getByRole("button", { name: "查看全部来源（5）", exact: true }).click();
  const allSources = preview.getByRole("region", { name: "全部来源", exact: true });
  assert.equal(await allSources.getByRole("button", { name: /^查看来源：/ }).count(), 5);
  await allSources.getByRole("button", { name: "查看来源：历史页面引用", exact: true }).click();
  await preview.getByRole("status").filter({ hasText: "该页面的历史快照不可用" }).waitFor();
  await preview.getByRole("button", { name: "返回任务上下文", exact: true }).click();
  await verifySubagentFlow(page, preview, scratch);
  checks.push("子代理入口先进入Active/Done列表，完成组可展开；历史区分运行/完成/未确认，返回保留展开、滚动和焦点；父子状态独立");
  checks.push("Thinking真实CSS采样显示左到右扫描，减少动效/系统偏好/隐藏停止；完成与待确认不显示Thinking");
  await preview.getByRole("button", { name: "展开关联项目 ZCode", exact: true }).click();
  await preview.getByText("/preview/workspace/ZCode", { exact: true }).waitFor();
  await sources.getByRole("button", { name: "折叠来源", exact: true }).click();
  assert.equal(await sources.getByRole("button", { name: /^查看来源：/ }).count(), 0);
  await sources.getByRole("button", { name: "展开来源", exact: true }).click();
  await preview.getByLabel("来源数量", { exact: true }).selectOption("3");
  assert.equal(await sources.getByRole("button", { name: /^查看来源：/ }).count(), 3);
  assert.equal(await sources.getByRole("button", { name: /查看全部来源/ }).count(), 0);
  await preview.getByLabel("来源数量", { exact: true }).selectOption("0");
  await sources.getByText("还没有输入来源", { exact: true }).waitFor();
  await sources.getByRole("button", { name: "添加来源", exact: true }).click();
  const adding = preview.getByRole("region", { name: "添加输入来源", exact: true });
  await adding.getByRole("button", { name: "添加示例网页到草稿", exact: true }).click();
  await sources.getByText("草稿待发送", { exact: true }).waitFor();
  await preview.getByLabel("来源数量", { exact: true }).selectOption("5");
  await preview.getByRole("tab", { name: "需要关注", exact: true }).click();
  await activity.click(); // Close the list: the warning must remain outside it.
  await preview.getByRole("status").filter({ hasText: "结果待核对" }).first().waitFor();
  await preview.getByRole("button", { name: "查看待核对记录", exact: true }).click();
  await preview.getByRole("heading", { name: "结果待核对", exact: true }).waitFor();
  await preview.getByRole("button", { name: "返回任务上下文", exact: true }).click();
  checks.push("关联项目可展开；来源三项/全部/折叠/空态和草稿添加可操作；异常在收起组外可发现且核对只读");
  await page.screenshot({ path: join(scratch, "conversation-system-attention.png"), fullPage: true });

  const draft = preview.getByTestId("system-preview-composer");
  await draft.fill("保留这段未发送的草稿");
  await page.getByLabel("面板宽度", { exact: true }).selectOption("narrow");
  const context = preview.getByRole("button", { name: "任务上下文", exact: true });
  if (await context.getAttribute("aria-expanded") === "false") await context.click();
  await preview.getByRole("button", { name: "查看全部 Subagents（16）", exact: true }).click();
  const narrowAgents = preview.getByRole("region", { name: "子代理面板", exact: true });
  await narrowAgents.getByRole("button", { name: /对话布局检查.*运行中/ }).click();
  await narrowAgents.getByRole("region", { name: "子代理历史对话", exact: true }).waitFor();
  await narrowAgents.getByRole("button", { name: "返回子代理列表", exact: true }).click();
  await narrowAgents.getByRole("button", { name: "关闭子代理面板", exact: true }).click();
  await preview.getByRole("button", { name: "返回对话", exact: true }).click();
  assert.equal(await draft.innerText(), "保留这段未发送的草稿");
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "任务上下文");
  for (const theme of ["light", "dark"]) {
    await page.getByLabel("主题", { exact: true }).selectOption(theme);
    await page.getByLabel("字号", { exact: true }).selectOption("18");
    await page.setViewportSize({ width: 420, height: 900 });
    await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
    await page.screenshot({ path: join(scratch, `conversation-system-${theme}-narrow.png`), fullPage: true });
  }
  await page.getByLabel("面板宽度", { exact: true }).selectOption("wide");
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.getByLabel("字号", { exact: true }).selectOption("14");
  await page.getByLabel("减少动态效果", { exact: true }).check();
  assert.equal(await activity.locator(".areal-disclosure-indicator").evaluate(element => getComputedStyle(element).transitionDuration), "0s");
  await preview.getByRole("tab", { name: "运行中", exact: true }).click();
  if (await activity.getAttribute("aria-expanded") === "true") await activity.click();
  if (await image.getAttribute("aria-expanded") === "true") await image.click();
  await preview.getByRole("region", { name: "示例对话", exact: true }).focus();
  await page.keyboard.press("Control+Home");
  await page.screenshot({ path: join(scratch, "conversation-system-dark-wide.png"), fullPage: true });
  checks.push("窄窗上下文返回保留草稿和焦点；420px大字号明暗主题无页面横向溢出；保存宽窄截图供视觉审查");
}

async function verifySubagentFlow(page, preview, scratch) {
  await preview.getByRole("button", { name: "查看全部 Subagents（16）", exact: true }).click();
  assert.equal(await preview.getByRole("button", { name: "任务上下文", exact: true }).getAttribute("aria-expanded"), "false");
  const panel = preview.getByRole("region", { name: "子代理面板", exact: true });
  await panel.getByRole("heading", { name: "Active · 1", exact: true }).waitFor();
  await panel.getByRole("heading", { name: "Done · 15", exact: true }).waitFor();
  assert.equal(await panel.locator('[data-agent-id]').count(), 11);
  await panel.getByRole("button", { name: "显示另外 5 个已完成子任务", exact: true }).click();
  assert.equal(await panel.locator('[data-agent-id]').count(), 16);
  const list = panel.locator('.areal-subagent-list');
  const lastAgent = panel.getByRole("button", { name: /操作边界核对.*已完成/ });
  await lastAgent.scrollIntoViewIfNeeded();
  const scrollTop = await list.evaluate(element => element.scrollTop);
  await lastAgent.click();
  await panel.getByRole("button", { name: "返回子代理列表", exact: true }).click();
  assert.equal(await list.evaluate(element => element.scrollTop), scrollTop);
  await page.screenshot({ path: join(scratch, "subagents-list.png"), fullPage: true });
  await panel.getByRole("button", { name: /对话布局检查.*运行中/ }).click();
  const history = panel.getByRole("region", { name: "子代理历史对话", exact: true });
  await history.getByText("检查活动分组、阅读返回和上下文来源，保留独立的子任务状态。", { exact: true }).waitFor();
  await history.getByText("Working for 2m 28s", { exact: true }).waitFor();
  await history.getByRole("status").filter({ hasText: "澄清动效与输出需求" }).waitFor();
  await preview.getByRole("button", { name: "推进摘要样例", exact: true }).click();
  await history.getByRole("status").filter({ hasText: "对比上下文卡片与资源面板" }).waitFor();
  await preview.getByLabel("过程摘要", { exact: true }).selectOption("long");
  assert.equal(await history.evaluate(element => element.scrollWidth <= element.clientWidth), true);
  await preview.getByLabel("过程摘要", { exact: true }).selectOption("thinking");
  await history.getByRole("status").filter({ hasText: "Thinking" }).waitFor();
  const thinking = history.locator('.areal-thinking');
  await thinking.scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('[aria-label="子代理历史对话"] .areal-thinking')?.dataset.animating === 'true');
  const positions = [];
  for (const time of [450, 900, 1350]) {
    positions.push(await thinking.evaluate((element, time) => {
      const sweep = element.querySelector('.areal-thinking-sweep');
      const animation = sweep.getAnimations()[0];
      animation.pause(); animation.currentTime = time;
      return parseFloat(getComputedStyle(sweep).maskPosition);
    }, time));
    await thinking.screenshot({ path: join(scratch, `thinking-${time}.png`) });
  }
  assert.ok(positions[0] > positions[1] && positions[1] > positions[2], "mask highlights move left to right with a 250% mask");
  await thinking.evaluate(element => element.querySelector('.areal-thinking-sweep').getAnimations()[0].play());
  await page.getByLabel("减少动态效果", { exact: true }).check();
  assert.equal(await thinking.locator('.areal-thinking-sweep').evaluate(element => getComputedStyle(element).animationName), 'none');
  await page.getByLabel("减少动态效果", { exact: true }).uncheck();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await thinking.locator('.areal-thinking-sweep').evaluate(element => getComputedStyle(element).animationName), 'none');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.screenshot({ path: join(scratch, "subagent-running.png"), fullPage: true });
  await panel.getByRole("button", { name: "返回子代理列表", exact: true }).click();
  assert.equal(await panel.locator('[data-agent-id]').count(), 16);
  await page.waitForFunction(() => document.activeElement?.getAttribute('data-agent-id') === 'layout');
  await panel.getByRole("button", { name: /活动合同核对.*已完成/ }).click();
  await history.getByText("Worked for 16m 18s", { exact: true }).waitFor();
  await history.getByRole("heading", { name: "活动合同核对完成", exact: true }).waitFor();
  assert.equal(await history.locator('.areal-thinking').count(), 0);
  await page.screenshot({ path: join(scratch, "subagent-completed.png"), fullPage: true });
  await panel.getByRole("button", { name: "返回子代理列表", exact: true }).click();
  await preview.getByLabel("子任务状态", { exact: true }).selectOption("completed");
  await panel.getByRole("heading", { name: "Active · 0", exact: true }).waitFor();
  await panel.getByText("没有运行中的子任务", { exact: true }).waitFor();
  await panel.getByRole("heading", { name: "Done · 16", exact: true }).waitFor();
  await preview.getByLabel("子任务状态", { exact: true }).selectOption("attention");
  await panel.getByRole("heading", { name: "Needs attention · 1", exact: true }).waitFor();
  await panel.getByRole("button", { name: /对话布局检查.*需要确认/ }).click();
  await history.getByRole("status").filter({ hasText: "退出结果尚未确认" }).waitFor();
  assert.equal(await history.locator('.areal-thinking').count(), 0);
  await preview.getByLabel("子任务状态", { exact: true }).selectOption("mixed");
  await preview.getByLabel("过程摘要", { exact: true }).selectOption("summary");
  await panel.getByRole("button", { name: "关闭子代理面板", exact: true }).click();
  await panel.waitFor({ state: "hidden" });
  await page.waitForFunction(() => document.querySelector('.areal-subagent-panel .areal-thinking')?.dataset.animating === 'false');
  // Parent is completed here; its running child stays running.
  await preview.getByText("1 个运行中 · 15 个已完成", { exact: true }).waitFor();
}
