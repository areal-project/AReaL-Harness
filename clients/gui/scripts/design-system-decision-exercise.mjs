import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { createHash } from "node:crypto";

export async function runDecisionExercise(page, scratch, gui, report) {
  Object.assign(report, { id: "decision-transfer", questionId: "Q-DECISION-TRANSFER-03", inputBaseSnapshot: "0b2cd5338a2342baf8d2851902d92ae106a8b468", candidateVersion: JSON.parse(await readFile(join(gui, "design-system/registry.json"), "utf8")).baseCandidate.version, briefSha256: createHash("sha256").update(await readFile(join(gui, "design-system/exercises/decision-transfer.md"))).digest("hex"), scope: "production content/decision components with local fixture actions", gaps: ["not blind or formal Base freeze", "no Codex decision same-state target or fidelity claim", "no Core/native/provider/package acceptance"] });
  const region = page.getByRole("region", { name: "内容决策迁移题", exact: true });
  const notes = region.getByRole("region", { name: "迁移说明", exact: true });
  const card = region.getByRole("region", { name: "工具审批", exact: true });
  const calls = region.getByLabel("本地调用记录", { exact: true });
  let previous = null, scenario = "light-wide-ready";
  const frame = async (id, action, readiness, target = card) => {
    await target.evaluate(element => element.scrollIntoView({ block: "center", inline: "nearest", behavior: "instant" }));
    const observation = await target.evaluate(element => {
      const rect = el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height }; };
      const box = rect(element), css = getComputedStyle(element);
      let fullyVisible = box.x >= 0 && box.y >= 0 && box.x + box.width <= innerWidth + 1 && box.y + box.height <= innerHeight + 1;
      for (let p = element.parentElement; p; p = p.parentElement) {
        const r = p.getBoundingClientRect(), c = getComputedStyle(p);
        if (/(auto|scroll|hidden|clip)/.test(c.overflowX) && (box.x < r.left - 1 || box.x + box.width > r.right + 1)) fullyVisible = false;
        if (/(auto|scroll|hidden|clip)/.test(c.overflowY) && (box.y < r.top - 1 || box.y + box.height > r.bottom + 1)) fullyVisible = false;
      }
      return { fullyVisible, box, text: element.textContent, fontSize: css.fontSize, color: css.color, background: css.backgroundColor, overflowX: element.scrollWidth > element.clientWidth + 1, buttons: [...element.querySelectorAll("button")].map(button => ({ label: button.getAttribute("aria-label") ?? button.textContent, disabled: button.disabled, box: rect(button) })), theme: document.documentElement.classList.contains("dark") ? "dark" : "light", uiFont: getComputedStyle(document.documentElement).getPropertyValue("--ui-font-size").trim(), viewport: { width: innerWidth, height: innerHeight, dpr: devicePixelRatio }, reducedMotion: document.documentElement.dataset.reducedMotion, desktopBridgePresent: typeof window.arealDesktop !== "undefined" };
    });
    observation.calls = await calls.innerText();
    await target.screenshot({ path: join(scratch, `${id}.png`), animations: "disabled" });
    await writeFile(join(scratch, `${id}.json`), JSON.stringify(observation, null, 2));
    report.steps.push({ id, scenario, from: previous, action, readiness, observedAt: new Date().toISOString(), observation: `${id}.json`, screenshot: { path: `${id}.png`, status: observation.fullyVisible ? "captured" : "partial" }, network: { status: "not_requested", reason: "fixture actions have no service claim" } });
    await writeFile(join(scratch, "exercise-steps.json"), JSON.stringify(report, null, 2));
    previous = id;
    assert.equal(observation.fullyVisible, true, "selected evidence target must be fully visible");
    assert.equal(observation.overflowX, false, "transfer component wraps within the container");
    assert.equal(observation.desktopBridgePresent, false);
    return observation;
  };
  await page.getByLabel("主题", { exact: true }).selectOption("light");
  const expand = notes.getByRole("button", { name: "展开全文", exact: true });
  await expand.waitFor();
  assert.equal(await expand.getAttribute("aria-expanded"), "false");
  const compact = await notes.locator(".collapsible-text-viewport").evaluate(el => ({ height: el.clientHeight, full: el.scrollHeight }));
  assert.ok(compact.full > compact.height * 2);
  await frame("notes-collapsed", "open fixed task", "long notes collapsed with explicit expand control", notes);
  await expand.focus(); await page.keyboard.press("Enter");
  const collapse = notes.getByRole("button", { name: "收起", exact: true });
  await collapse.waitFor();
  const full = await notes.locator(".collapsible-text-viewport").evaluate(el => ({ height: el.clientHeight, full: el.scrollHeight, text: el.textContent }));
  assert.ok(full.full <= full.height + 1 && full.text.includes("检查项 12"));
  const tail = notes.getByRole("link", { name: "核对末段 END_OF_TRANSFER_NOTES", exact: true });
  await frame("notes-expanded-tail", "keyboard Enter on expand", "complete final paragraph retained and scrolled into view", notes.locator(".collapsible-text-content p").last());
  await collapse.focus(); await page.keyboard.press("Space"); await expand.waitFor();
  assert.equal(await expand.evaluate(el => el === document.activeElement), true);
  await tail.focus(); await collapse.waitFor();
  assert.equal(await collapse.getAttribute("aria-expanded"), "true", "clipped link focus expands the complete content");
  await collapse.click();
  report.checks.push("new long notes: bounded preview, keyboard full text, focus-preserving collapse and focused-tail expansion");
  assert.equal(await card.locator("details").first().getAttribute("open"), null);
  await card.getByText("查看完整请求", { exact: true }).click();
  await frame("ready", "collapse notes; inspect original parameters", "ready request with full command");
  const original = await card.locator(".approval-preview").textContent();
  assert.ok(original.includes("configuration.json") && original.includes("verify parameters before continuing"));
  await card.getByRole("button", { name: "允许一次", exact: true }).focus(); await page.keyboard.press("Enter");
  await card.getByRole("status").waitFor();
  assert.ok((await card.getByRole("status").innerText()).includes("已提交，等待执行状态更新"));
  assert.equal(await card.getByRole("button", { name: "允许一次", exact: true }).isDisabled(), true);
  assert.ok((await calls.innerText()).includes("模拟响应：1；模拟核对：0"));
  await frame("acknowledged", "keyboard approve once", "receipt locks actions but request remains awaiting execution projection");
  report.checks.push("acknowledgement retains the card and original parameters, without fabricating execution completion");
  scenario = "dark-narrow-failed"; previous = null;
  await page.getByLabel("主题", { exact: true }).selectOption("dark");
  await page.getByLabel("字号", { exact: true }).selectOption("18");
  await page.getByLabel("面板宽度", { exact: true }).selectOption("narrow");
  await page.getByLabel("状态", { exact: true }).selectOption("failed");
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.decision-card')).fontSize === "18px" && document.documentElement.classList.contains("dark"));
  const narrow = await frame("narrow-ready", "independent failed scenario; dark18 narrow", "original command wrapped and decision buttons reachable");
  assert.equal(narrow.fontSize, "18px");
  assert.ok(narrow.box.width < 400);
  for (const b of narrow.buttons) assert.ok(b.box.x >= narrow.box.x && b.box.x + b.box.width <= narrow.box.x + narrow.box.width + 1);
  assert.equal(await card.locator(".approval-preview").textContent(), original);
  await card.getByText("查看完整请求", { exact: true }).click();
  const body = card.locator(".decision-card-body");
  const scroll = await body.evaluate(el => ({ height: el.clientHeight, full: el.scrollHeight, horizontalOverflow: el.scrollWidth > el.clientWidth + 1 }));
  assert.equal(scroll.horizontalOverflow, false);
  assert.ok(scroll.full > scroll.height, "narrow request uses the existing bounded scroll body");
  await body.hover(); await page.mouse.wheel(0, 1000);
  await page.waitForFunction(() => { const el = document.querySelector('.decision-card-body'); return el.scrollTop + el.clientHeight >= el.scrollHeight - 1; });
  await frame("narrow-parameters-end", "wheel within existing request body", "last purpose parameter visible; footer remains outside the scroll body");
  await body.evaluate(el => el.scrollTo(0, 0));
  await card.getByRole("button", { name: "允许一次", exact: true }).click();
  const failureToast = page.getByTestId("toast").getByRole("alert");
  await failureToast.waitFor();
  assert.ok((await failureToast.innerText()).includes("明确未受理"));
  assert.equal(await card.getByRole("button", { name: "允许一次", exact: true }).isEnabled(), true);
  await card.getByRole("button", { name: "允许一次", exact: true }).click();
  assert.ok((await calls.innerText()).includes("模拟响应：2；模拟核对：0"));
  await frame("failed-retry", "explicit failure; retry once", "same parameters and failure retained after two fixture responses");
  report.checks.push("dark18 narrow: full parameters wrap, actions remain contained; explicit failure allows deliberate retry");
  scenario = "dark-narrow-busy"; previous = null;
  await page.getByLabel("状态", { exact: true }).selectOption("busy");
  await card.getByRole("button", { name: "允许一次", exact: true }).click();
  await card.getByText("提交中…", { exact: true }).waitFor();
  assert.equal(await card.getAttribute("aria-busy"), "true");
  assert.equal(await card.getByRole("button", { name: "拒绝", exact: true }).isDisabled(), true);
  assert.equal(await card.getByRole("button", { name: "提交中…", exact: true }).isDisabled(), true);
  await card.focus(); await page.keyboard.press("Escape");
  assert.ok((await calls.innerText()).includes("模拟响应：1；模拟核对：0"));
  await frame("busy", "independent pending scenario; approve then Escape", "busy locks both decisions; fixture received one response");
  report.checks.push("busy decision blocks a second response including keyboard dismissal");
  scenario = "dark-narrow-unknown"; previous = null;
  await page.getByLabel("状态", { exact: true }).selectOption("unknown");
  await card.getByRole("button", { name: "允许一次", exact: true }).click();
  const reconcile = card.getByRole("button", { name: "核对待审批状态", exact: true });
  await reconcile.waitFor();
  assert.equal(await card.getByRole("button", { name: "允许一次", exact: true }).count(), 0);
  await frame("unknown", "independent unknown scenario; approve once", "only reconciliation offered, full command retained");
  await reconcile.focus(); await page.keyboard.press("Enter");
  await page.getByTestId("toast").getByRole("alert").filter({ hasText: "无法核对审批状态" }).waitFor();
  assert.equal(await card.getByRole("button", { name: "允许一次", exact: true }).count(), 0);
  assert.ok((await calls.innerText()).includes("模拟响应：1；模拟核对：1"));
  assert.equal(await card.locator(".approval-preview").textContent(), original);
  await frame("reconcile-failed", "keyboard reconcile; fixture read rejects", "unknown preserved and no response replay");
  report.checks.push("unknown only reconciles; failed read preserves uncertainty and original parameters without replay");
  await writeFile(join(scratch, "exercise-steps.json"), JSON.stringify(report, null, 2));
}
